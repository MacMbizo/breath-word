// AudioEngineAdapter — dual-track narration + ambient audio over HTML5 `Audio` (B3 §4.3).
//
// Narration is one `Audio` element; ambient beds (rain/piano/pad) are a second, looping element.
// Playback-policy rejections (the browser requiring a user gesture) are swallowed rather than
// surfaced — audio is non-critical and `ErrorDomain` has no `AUDIO` member (C3), so there is no
// canonical error to raise. The sleep timer fades both tracks out along the shared core curve
// (`sleepFadeGain`, FR-106) and then pauses them.

import { SLEEP_FADE_STEP_MS, sleepFadeGain, type AudioEngineAdapter } from '@breath-and-word/core';

type AmbientTrack = 'none' | 'rain' | 'piano' | 'pad';

/**
 * Ambient bed assets shipped with the app bundle (B3 §4.1 `apps/desktop/public`), generated by
 * `tools/pack-builder/scripts/generate-ambient.mjs` as seamless loops.
 */
const AMBIENT_SOURCES: Record<Exclude<AmbientTrack, 'none'>, string> = {
  rain: '/audio/ambient/rain.wav',
  piano: '/audio/ambient/piano.wav',
  pad: '/audio/ambient/pad.wav',
};

function clamp01(volume: number): number {
  if (volume < 0) return 0;
  if (volume > 1) return 1;
  return volume;
}

/** Autoplay may be blocked until the user interacts; never let that reject the adapter call. */
function ignorePlaybackRejection(playback: Promise<void> | undefined): void {
  if (playback === undefined) return;
  void playback.catch((cause: unknown) => {
    // Non-critical, but say why in development so silent audio is diagnosable.
    if (import.meta.env.DEV) console.warn('[audio] playback rejected', cause);
  });
}

export function createAudioAdapter(): AudioEngineAdapter {
  let narration: HTMLAudioElement | null = null;
  let ambient: HTMLAudioElement | null = null;
  let sleepFade: ReturnType<typeof setInterval> | null = null;
  /** True between play() and pause(): the ambient bed follows this, with or without narration. */
  let playing = false;
  /** User-chosen levels; the element volume is `level × fade gain`. */
  let narrationLevel = 1;
  let ambientLevel = 0;
  let fadeGain = 1;
  const positionListeners = new Set<(positionMs: number) => void>();

  function applyVolumes(): void {
    if (narration !== null) narration.volume = clamp01(narrationLevel * fadeGain);
    if (ambient !== null) ambient.volume = clamp01(ambientLevel * fadeGain);
  }

  function clearSleepFade(): void {
    if (sleepFade !== null) {
      clearInterval(sleepFade);
      sleepFade = null;
    }
    fadeGain = 1;
    applyVolumes();
  }

  function emitPosition(positionMs: number): void {
    for (const listener of positionListeners) {
      listener(positionMs);
    }
  }

  return {
    async loadChapter(urlOrPath, title, subtitle): Promise<void> {
      narration?.pause();
      const element = new Audio(urlOrPath);
      element.preload = 'auto';
      // Surface the chapter metadata on the element for now-playing UI / media session.
      element.dataset['bwTitle'] = title;
      element.dataset['bwSubtitle'] = subtitle;
      element.addEventListener('timeupdate', () => emitPosition(element.currentTime * 1000));
      narration = element;
      applyVolumes();
    },

    async play(): Promise<void> {
      playing = true;
      ignorePlaybackRejection(narration?.play());
      ignorePlaybackRejection(ambient?.play());
    },

    async pause(): Promise<void> {
      playing = false;
      narration?.pause();
      ambient?.pause();
    },

    async seekTo(ms): Promise<void> {
      if (narration !== null) {
        narration.currentTime = ms / 1000;
      }
    },

    async setPlaybackRate(rate): Promise<void> {
      if (narration !== null) {
        narration.playbackRate = rate;
      }
    },

    async setAmbientTrack(trackId, volume): Promise<void> {
      if (trackId === 'none') {
        ambient?.pause();
        ambient = null;
        return;
      }
      const source = AMBIENT_SOURCES[trackId];
      if (ambient === null || ambient.getAttribute('src') !== source) {
        ambient?.pause();
        ambient = new Audio(source);
        ambient.loop = true;
        ambient.preload = 'auto';
        if (import.meta.env.DEV) {
          const element = ambient;
          element.addEventListener('error', () => console.warn('[audio] ambient failed to load', source, element.error));
        }
      }
      ambientLevel = clamp01(volume);
      applyVolumes();
      if (playing) ignorePlaybackRejection(ambient.play());
    },

    async setNarrationVolume(volume): Promise<void> {
      narrationLevel = clamp01(volume);
      applyVolumes();
    },

    async setSleepTimer(minutes): Promise<void> {
      clearSleepFade();
      if (minutes === null) return;
      const timerMs = minutes * 60_000;
      const armedAt = Date.now();
      // Sample the fade curve on a short interval; full volume until the last stretch, then an
      // even ramp to silence, then pause and restore the levels for the next listen.
      sleepFade = setInterval(() => {
        const elapsed = Date.now() - armedAt;
        fadeGain = sleepFadeGain(elapsed, timerMs);
        applyVolumes();
        if (elapsed >= timerMs) {
          playing = false;
          narration?.pause();
          ambient?.pause();
          clearSleepFade();
        }
      }, SLEEP_FADE_STEP_MS);
    },

    onPositionUpdate(cb): () => void {
      positionListeners.add(cb);
      return () => {
        positionListeners.delete(cb);
      };
    },
  };
}
