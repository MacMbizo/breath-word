// FR-102 parallel multi-translation compare — loads one canonical verse across several
// (pack, translation) refs through the headless reader store and renders the columns side
// by side. No SQL here (AGENTS.md rule 1): the store calls `ReaderRepository`.
import { useState, type FormEvent } from 'react';

import {
  formatCanonicalRange,
  toCanonicalVerseId,
  type TranslationRef,
} from '@breath-and-word/core';

import { useCoreRuntime } from './CoreRuntime';
import { useCoreStore } from './useCoreStore';
import { VerseSpans } from './VerseSpans';

// Each ref is `packId:translationCode`; several refs can share a pack. Defaults open
// Romans 8:28 in the BSB pack generated by tools/pack-builder.
const DEFAULT_REFS = 'core_bsb:BSB';
const DEFAULT_BOOK = '45';
const DEFAULT_CHAPTER = '8';
const DEFAULT_VERSE = '28';

const FIELD =
  'w-full rounded-md border border-hairline bg-surface px-md py-sm font-ui text-uiSm text-ink-primary outline-none focus:border-accent';

function parseRefs(input: string): TranslationRef[] {
  return input
    .split(',')
    .map((entry) => entry.trim())
    .filter((entry) => entry.length > 0)
    .map((entry) => {
      const [packId = '', translationCode = ''] = entry.split(':').map((part) => part.trim());
      return { packId, translationCode };
    })
    .filter((ref) => ref.packId.length > 0 && ref.translationCode.length > 0);
}

export function CompareView() {
  const { stores } = useCoreRuntime();
  const { comparison, comparisonStatus } = useCoreStore(stores.reader);
  const [refsInput, setRefsInput] = useState(DEFAULT_REFS);
  const [book, setBook] = useState(DEFAULT_BOOK);
  const [chapter, setChapter] = useState(DEFAULT_CHAPTER);
  const [verse, setVerse] = useState(DEFAULT_VERSE);

  const refs = parseRefs(refsInput);
  const canonicalVerseId = toCanonicalVerseId({
    book: Number(book),
    chapter: Number(chapter),
    verse: Number(verse),
  });

  function onSubmit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    void stores.reader.getState().compareVerses(refs, canonicalVerseId);
  }

  return (
    <section className="flex h-full flex-col gap-lg overflow-hidden">
      <form onSubmit={onSubmit} className="flex flex-wrap items-end gap-sm">
        <label className="flex min-w-64 flex-1 flex-col gap-xxs font-ui text-uiXs text-ink-secondary">
          Translations (packId:code, comma-separated)
          <input
            className={FIELD}
            value={refsInput}
            placeholder="core_bsb:BSB, core_kjv:KJV"
            onChange={(e) => setRefsInput(e.target.value)}
          />
        </label>
        <label className="flex w-24 flex-col gap-xxs font-ui text-uiXs text-ink-secondary">
          Book
          <input
            className={FIELD}
            inputMode="numeric"
            value={book}
            onChange={(e) => setBook(e.target.value)}
          />
        </label>
        <label className="flex w-24 flex-col gap-xxs font-ui text-uiXs text-ink-secondary">
          Chapter
          <input
            className={FIELD}
            inputMode="numeric"
            value={chapter}
            onChange={(e) => setChapter(e.target.value)}
          />
        </label>
        <label className="flex w-24 flex-col gap-xxs font-ui text-uiXs text-ink-secondary">
          Verse
          <input
            className={FIELD}
            inputMode="numeric"
            value={verse}
            onChange={(e) => setVerse(e.target.value)}
          />
        </label>
        <button
          type="submit"
          className="rounded-md bg-accent px-lg py-sm font-ui text-uiSm font-medium text-canvas transition hover:opacity-90"
        >
          Compare
        </button>
      </form>

      <div className="flex-1 overflow-y-auto">
        {comparisonStatus === 'loading' && (
          <p className="font-ui text-uiSm text-ink-secondary">Loading columns…</p>
        )}
        {comparisonStatus === 'error' && (
          <p className="font-ui text-uiSm text-ink-red" role="alert">
            The columns could not be loaded.
          </p>
        )}
        {comparisonStatus === 'idle' && (
          <p className="font-ui text-uiSm text-ink-secondary">
            Add one or more translations and a verse, then compare side by side.
          </p>
        )}
        {comparisonStatus === 'ready' && (
          <div className="flex flex-col gap-md">
            <p className="font-ui text-uiSm text-ink-secondary">
              {formatCanonicalRange(canonicalVerseId, canonicalVerseId)}
            </p>
            <div
              className="grid gap-lg"
              style={{ gridTemplateColumns: `repeat(${Math.max(refs.length, 1)}, minmax(0, 1fr))` }}
            >
              {refs.map((ref) => {
                const match = comparison.find(
                  (candidate) => candidate.translationCode === ref.translationCode,
                );
                return (
                  <article
                    key={`${ref.packId}:${ref.translationCode}`}
                    className="rounded-md border border-hairline bg-surface px-lg py-md"
                  >
                    <h3 className="mb-sm font-ui text-uiXs uppercase tracking-wide text-ink-secondary">
                      {ref.translationCode}
                    </h3>
                    {match === undefined ? (
                      <p className="font-ui text-uiSm text-ink-secondary">
                        Not available in this pack.
                      </p>
                    ) : (
                      <p className="font-scripture text-ink-primary" style={{ lineHeight: 1.72 }}>
                        <VerseSpans verseId={match.canonicalVerseId} spans={match.spans} />
                      </p>
                    )}
                  </article>
                );
              })}
            </div>
          </div>
        )}
      </div>
    </section>
  );
}
