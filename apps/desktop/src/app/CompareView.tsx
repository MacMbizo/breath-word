// FR-102 parallel multi-translation compare — loads one chapter across several (pack, translation)
// refs through the headless reader store and renders them as verse-synchronized columns. The columns
// share ONE scroll surface built from a row-per-verse grid (`alignChapterVerses`), so a verse lines
// up across every column by construction. No SQL here (AGENTS.md rule 1): the store calls
// `ReaderRepository`.
import { useState, type FormEvent } from 'react';

import { bookName, type TranslationRef } from '@breath-and-word/core';

import { useCoreRuntime } from './CoreRuntime';
import { useCoreStore } from './useCoreStore';
import { VerseSpans } from './VerseSpans';

// Each ref is `packId:translationCode`; several refs can share a pack. Defaults open Romans 8 in
// the `core_bsb` pack generated by tools/pack-builder.
const DEFAULT_REFS = 'core_bsb:BSB';
const DEFAULT_BOOK = '45';
const DEFAULT_CHAPTER = '8';

const FIELD =
  'w-full rounded-md border border-hairline bg-surface px-md py-sm font-ui text-uiSm text-ink-primary outline-none focus:border-accent';
const LABEL = 'flex flex-col gap-xxs font-ui text-uiXs text-ink-secondary';

function parseRefs(input: string): TranslationRef[] {
  return input
    .split(',')
    .map((entry) => entry.trim())
    .filter((entry) => entry.length > 0)
    .map((entry) => {
      const [packId = '', translationCode = ''] = entry.split(':').map((part) => part.trim());
      return { packId, translationCode };
    })
    .filter((ref) => ref.packId.length > 0 && ref.translationCode.length > 0);
}

export function CompareView() {
  const { stores } = useCoreRuntime();
  const { comparisonRows, comparisonStatus } = useCoreStore(stores.reader);
  const [refsInput, setRefsInput] = useState(DEFAULT_REFS);
  const [book, setBook] = useState(DEFAULT_BOOK);
  const [chapter, setChapter] = useState(DEFAULT_CHAPTER);

  const refs = parseRefs(refsInput);
  const bookNumber = Number(book);
  const chapterNumber = Number(chapter);
  // A shared column template: a narrow verse-number gutter, then one column per translation.
  const gridTemplateColumns = `2rem repeat(${Math.max(refs.length, 1)}, minmax(0, 1fr))`;

  function onSubmit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    void stores.reader.getState().compareChapters(refs, bookNumber, chapterNumber);
  }

  return (
    <section className="flex h-full flex-col gap-lg overflow-hidden">
      <form onSubmit={onSubmit} className="flex flex-wrap items-end gap-sm">
        <label className={`${LABEL} min-w-64 flex-1`}>
          Translations (packId:code, comma-separated)
          <input
            className={FIELD}
            value={refsInput}
            placeholder="core_bsb:BSB, trans_kjv:KJV"
            onChange={(e) => setRefsInput(e.target.value)}
          />
        </label>
        <label className={`${LABEL} w-24`}>
          Book
          <input
            className={FIELD}
            inputMode="numeric"
            value={book}
            onChange={(e) => setBook(e.target.value)}
          />
        </label>
        <label className={`${LABEL} w-24`}>
          Chapter
          <input
            className={FIELD}
            inputMode="numeric"
            value={chapter}
            onChange={(e) => setChapter(e.target.value)}
          />
        </label>
        <button
          type="submit"
          className="rounded-md bg-accent px-lg py-sm font-ui text-uiSm font-medium text-canvas transition hover:opacity-90"
        >
          Compare
        </button>
      </form>

      <div className="flex-1 overflow-y-auto">
        {comparisonStatus === 'loading' && (
          <p className="font-ui text-uiSm text-ink-secondary">Loading columns…</p>
        )}
        {comparisonStatus === 'error' && (
          <p className="font-ui text-uiSm text-ink-red" role="alert">
            The columns could not be loaded.
          </p>
        )}
        {comparisonStatus === 'idle' && (
          <p className="font-ui text-uiSm text-ink-secondary">
            Choose one or more translations and a chapter, then compare side by side.
          </p>
        )}
        {comparisonStatus === 'ready' && (
          <div className="flex flex-col">
            <p className="mb-sm font-ui text-uiSm text-ink-secondary">
              {bookName(bookNumber)} {chapterNumber}
            </p>
            <div
              className="sticky top-0 z-10 grid gap-lg border-b border-hairline bg-canvas pb-sm"
              style={{ gridTemplateColumns }}
            >
              <span />
              {refs.map((ref) => (
                <span
                  key={`${ref.packId}:${ref.translationCode}`}
                  className="font-ui text-uiXs uppercase tracking-wide text-ink-secondary"
                >
                  {ref.translationCode}
                </span>
              ))}
            </div>
            {comparisonRows.map((row) => (
              <div
                key={row.canonicalVerseId}
                className="grid items-start gap-lg border-b border-hairline py-sm"
                style={{ gridTemplateColumns }}
              >
                <span className="font-ui text-uiXs text-ink-verse">{row.verse}</span>
                {row.cells.map((cell, index) => (
                  <p
                    key={index}
                    className="font-scripture text-ink-primary"
                    style={{ lineHeight: 1.72 }}
                  >
                    {cell === undefined ? (
                      <span className="font-ui text-uiXs text-ink-secondary">—</span>
                    ) : (
                      <VerseSpans verseId={cell.canonicalVerseId} spans={cell.spans} />
                    )}
                  </p>
                ))}
              </div>
            ))}
          </div>
        )}
      </div>
    </section>
  );
}
