// FR-102 parallel multi-translation compare (mobile) — loads one chapter across several
// (pack, translation) refs through the headless reader store and renders every translation stacked
// under each verse on ONE scroll surface (`alignChapterVerses`), so verses line up across
// translations by construction. No SQL here (AGENTS.md rule 1): the store calls `ReaderRepository`.

import { useState } from 'react';
import { Pressable, ScrollView, Text, TextInput, View } from 'react-native';

import { bookName, type TranslationRef } from '@breath-and-word/core';
import { FONT_FACES, FONT_SIZES, LINE_HEIGHTS, MIN_TOUCH_TARGET, RADII, SPACING } from '@breath-and-word/tokens';

import { useCoreRuntime } from './CoreRuntime';
import { useCoreStore } from './useCoreStore';
import { VerseSpans } from './VerseSpans';
import { makeStyles, useTheme } from '../theme/ThemeProvider';

/** The default (daylight) theme; theme switching lands with the appearance settings. */

// Each ref is `packId:translationCode`; several refs can share a pack. Defaults open Romans 8 in the
// `core_bsb` pack generated by tools/pack-builder.
const DEFAULT_REFS = 'core_bsb:BSB';
const DEFAULT_BOOK = '45';
const DEFAULT_CHAPTER = '8';

function parseRefs(input: string): TranslationRef[] {
  return input
    .split(',')
    .map((entry) => entry.trim())
    .filter((entry) => entry.length > 0)
    .map((entry) => {
      const [packId = '', translationCode = ''] = entry.split(':').map((part) => part.trim());
      return { packId, translationCode };
    })
    .filter((ref) => ref.packId.length > 0 && ref.translationCode.length > 0);
}

export function CompareScreen() {
  const styles = useStyles();
  const { colors: THEME } = useTheme();
  const runtime = useCoreRuntime();
  const { comparisonRows, comparisonStatus } = useCoreStore(runtime.stores.reader);
  const [refsInput, setRefsInput] = useState(DEFAULT_REFS);
  const [book, setBook] = useState(DEFAULT_BOOK);
  const [chapter, setChapter] = useState(DEFAULT_CHAPTER);

  const refs = parseRefs(refsInput);
  const bookNumber = Number(book);
  const chapterNumber = Number(chapter);

  function compare() {
    void runtime.stores.reader.getState().compareChapters(refs, bookNumber, chapterNumber);
  }

  return (
    <View style={styles.root}>
      <View style={styles.header}>
        <Text style={styles.title}>Compare translations</Text>
        <View style={styles.field}>
          <Text style={styles.label}>Translations (packId:code, comma-separated)</Text>
          <TextInput
            style={styles.input}
            value={refsInput}
            autoCapitalize="none"
            autoCorrect={false}
            placeholder="core_bsb:BSB, trans_kjv:KJV"
            placeholderTextColor={THEME.text.verseNum}
            onChangeText={setRefsInput}
          />
        </View>
        <View style={styles.refRow}>
          <View style={[styles.field, styles.refField]}>
            <Text style={styles.label}>Book</Text>
            <TextInput
              style={styles.input}
              inputMode="numeric"
              value={book}
              onChangeText={setBook}
            />
          </View>
          <View style={[styles.field, styles.refField]}>
            <Text style={styles.label}>Chapter</Text>
            <TextInput
              style={styles.input}
              inputMode="numeric"
              value={chapter}
              onChangeText={setChapter}
            />
          </View>
          <Pressable onPress={compare} accessibilityRole="button" style={styles.submitButton}>
            <Text style={styles.submitButtonText}>Compare</Text>
          </Pressable>
        </View>
      </View>

      <ScrollView contentContainerStyle={styles.content}>
        {comparisonStatus === 'loading' && <Text style={styles.muted}>Loading columns…</Text>}
        {comparisonStatus === 'error' && (
          <Text accessibilityRole="alert" style={styles.error}>
            The columns could not be loaded.
          </Text>
        )}
        {comparisonStatus === 'idle' && (
          <Text style={styles.muted}>
            Choose one or more translations and a chapter, then compare side by side.
          </Text>
        )}
        {comparisonStatus === 'ready' && (
          <>
            <Text style={styles.reference}>
              {bookName(bookNumber)} {chapterNumber}
            </Text>
            {comparisonRows.map((row) => (
              <View key={row.canonicalVerseId} style={styles.row}>
                <Text style={styles.verseNumber}>{row.verse}</Text>
                {row.cells.map((cell, index) => (
                  <View key={index} style={styles.cell}>
                    <Text style={styles.cellHeading}>{refs[index]?.translationCode ?? ''}</Text>
                    {cell === undefined ? (
                      <Text style={styles.muted}>Not in this translation.</Text>
                    ) : (
                      <Text style={styles.verse}>
                        <VerseSpans verseId={cell.canonicalVerseId} spans={cell.spans} />
                      </Text>
                    )}
                  </View>
                ))}
              </View>
            ))}
          </>
        )}
      </ScrollView>
    </View>
  );
}

